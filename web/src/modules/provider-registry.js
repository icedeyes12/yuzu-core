const providers = Object.freeze(
	Object.fromEntries(
		providerDefinitions.map((provider) => [
			provider.id,
			Object.freeze(provider),
		]),
	),
);

const fallbackProvider = Object.freeze({
	id: "unknown",
	displayName: "Unknown provider",
	shortName: "Unknown",
	family: "Unknown",
	logo: null,
	fallbackLogo: "??",
	accentColor: null,
	badge: "unknown",
	supportsDark: true,
	custom: false,
	experimental: false,
	deprecated: false,
});

export const ProviderRegistry = Object.freeze({
	providers,
	fallback: fallbackProvider,
	get(id) {
		return providers[id] || fallbackProvider;
	},
	list() {
		return Object.values(providers);
	},
});

export const getProvider = ProviderRegistry.get.bind(ProviderRegistry);
export const listProviders = ProviderRegistry.list.bind(ProviderRegistry);
